const { chromium } = require('C:/Users/94719/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.connectOverCDP('http://127.0.0.1:19224')
  try {
    const page = browser.contexts().flatMap((context) => context.pages()).find((item) => item.url().includes('/home'))
    assert(page, 'EM home window must be present')
    assert.equal(new URL(page.url()).origin, 'http://tauri.localhost')
    page.setDefaultTimeout(20000)
    const controls = await page.locator('textarea, input:not([type=password])').evaluateAll((elements) => elements.filter((element) => element.getBoundingClientRect().width && element.value.trim()).length)
    assert.equal(controls, 0, 'Leave any active user input untouched')
    await page.goto('http://tauri.localhost/home/message')
    await page.waitForLoadState('domcontentloaded')
    await page.locator('.local-chat').waitFor()
    const groupName = await page.evaluate(() => {
      const data = JSON.parse(localStorage.getItem('em.local-chat.v1'))
      const current = data.conversations.find((chat) => chat.id === data.selectedId && !chat.peerId)
      return (current || data.conversations.find((chat) => !chat.peerId))?.name
    })
    assert(groupName, 'An existing local group is required; do not seed user data')
    await page.locator('.conversation').filter({ has: page.locator('strong', { hasText: groupName }) }).first().click()
    const entry = page.getByRole('button', { name: '问问本群', exact: true })
    await entry.waitFor({ state: 'visible' })
    await entry.click()
    await page.locator('.knowledge-panel').waitFor()
    await page.waitForFunction(() => /已读取本机|无法读取|保存错误/.test(document.querySelector('.knowledge-panel')?.textContent || ''))
    const coverage = await page.locator('.knowledge-panel .coverage').innerText()
    assert.match(coverage, /已读取本机/)
    for (const command of ['plugin:window|unminimize', 'plugin:window|show', 'plugin:window|set_focus'])
      await page.evaluate((command) => window.__TAURI_INTERNALS__.invoke(command, { label: 'home' }), command)
    await page.screenshot({ path: '.preview/chat-knowledge/installed-client-entry.png', fullPage: true })
    console.log(JSON.stringify({ verified: true, origin: new URL(page.url()).origin, groupName, coverage, modelCalled: false }, null, 2))
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
