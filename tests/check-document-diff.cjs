// Isolated storage; only synthetic documents and a mocked AI response.
const { chromium } = require('C:/Users/94719/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const output = path.resolve('.preview/office-verification', `diff-${Date.now()}`)
fs.mkdirSync(output, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  try {
    let calls = 0
    await page.addInitScript(() => localStorage.setItem('em.local-ai.v1', JSON.stringify({ baseUrl: 'http://127.0.0.1:19442/v1', model: 'diff-fixture' })))
    await page.route('**/@tauri-apps_plugin-http.js*', r => r.fulfill({ contentType: 'text/javascript', body: 'export const fetch = globalThis.fetch.bind(globalThis);' }))
    await page.route('http://127.0.0.1:19442/v1/chat/completions', r => {
      calls++
      const input = JSON.parse(JSON.parse(r.request().postData()).messages[1].content)
      assert.equal(input.documents[0].role, '基准 / 旧版')
      assert.equal(input.documents[1].role, '新版 / 待比对')
      r.fulfill({ contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { content: JSON.stringify({ summary: '模拟条款分析', findings: [{ title: '保存期限修改', detail: '3年改为5年', suggestion: '请人工核验', refs: input.documents.map(d => ({ id: d.paragraphs[0].id, quote: d.paragraphs[0].text })) }], draft: '模拟修订草稿' }) } }] }) })
    })
    await page.goto('http://127.0.0.1:1425/tests/compliance-preview.html')
    await page.getByRole('button', { name: '制度比对', exact: true }).click()
    async function add(name, text) {
      await page.getByLabel('资料名称', { exact: true }).fill(name)
      await page.getByLabel('资料全文', { exact: true }).fill(text)
      await page.getByRole('button', { name: '保存资料到本机', exact: true }).click()
      await page.locator('.cw-library-item').filter({ hasText: name }).waitFor()
    }
    const before = '第一条 记录保存3年。\n\n第二条 每季度检查。\n\n第三条 本条保留。\n\n第四条 旧条款删除。'
    const after = '第一条 记录保存5年。\n\n第二条 每月检查。\n\n第三条 本条保留。\n\n第四条 新增整改记录。\n\n第五条 <script>仅为文字</script>'
    await add('基准制度（合成自测）', before)
    await add('新版制度（合成自测）', after)
    await page.getByRole('button', { name: /收起资料库/ }).click()
    await page.locator('.document-diff').waitFor()
    assert.equal(calls, 0, 'text comparison must not require a model')
    assert.match((await page.locator('.diff-left mark').allTextContents()).join(''), /3/)
    assert.match((await page.locator('.diff-right mark').allTextContents()).join(''), /5/)
    assert.match(await page.locator('.document-diff').innerText(), /<script>仅为文字<\/script>/)
    assert.equal(await page.locator('.document-diff script').count(), 0)
    await page.getByLabel('只看差异', { exact: true }).check()
    assert.equal(await page.locator('.diff-same').count(), 0)
    await page.getByLabel('只看差异', { exact: true }).uncheck()
    assert(await page.locator('.diff-same').count() > 0)
    await page.getByRole('button', { name: '交换左右', exact: true }).click()
    assert.match(await page.locator('.diff-titles strong').first().innerText(), /新版制度/)
    await page.getByRole('button', { name: '交换左右', exact: true }).click()
    await page.getByLabel('合规任务说明').fill('对照两份制度，解释修改。')
    await page.locator('.cw-consent input').check()
    await page.getByRole('button', { name: '开始分析', exact: true }).click()
    await page.locator('.cw-finding').waitFor()
    assert.equal(calls, 1)
    await page.getByLabel('人工处理', { exact: true }).selectOption('已接受')
    await page.getByLabel('合规草稿').fill('人工核验后的测试草稿')
    await page.getByRole('button', { name: '保存审核与草稿', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: '制度比对', exact: true }).click()
    await page.locator('.cw-history').first().click()
    await page.locator('.document-diff').waitFor()
    assert.equal(await page.getByLabel('差异来源').inputValue(), 'result')
    assert.equal(await page.getByLabel('人工处理', { exact: true }).inputValue(), '已接受')
    assert.equal(await page.getByLabel('合规草稿').inputValue(), '人工核验后的测试草稿')
    await page.screenshot({ path: path.join(output, 'comparison.png'), fullPage: true })
    assert.deepEqual(errors, [])
    console.log(`PASS: local diff, Chinese highlights, swapped sides, additions/deletions, safe text rendering, unchanged filtering, AI roles and snapshot/review persistence. Evidence: ${output}`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
