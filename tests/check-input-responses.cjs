const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const runtime = process.env.EM_PLAYWRIGHT_MODULE || path.join(require('node:os').homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const { chromium } = require(runtime)
const desktopSource = fs.readFileSync(path.join(__dirname, '../src/utils/desktop/window.ts'), 'utf8')
const desktopStub = [...desktopSource.matchAll(/export\s+(?:async\s+)?(?:const|function)\s+(\w+)/g)]
  .map(match => `export const ${match[1]}=async()=>false;`).join('\n')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage()
  page.setDefaultTimeout(20000)
  const errors = []
  page.on('pageerror', error => { if (!error.message.startsWith('ResizeObserver loop')) errors.push(error.message) })
  const origin = process.env.EM_TEST_ORIGIN || 'http://127.0.0.1:1425'
  try {
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      return ['127.0.0.1', 'localhost'].includes(url.hostname) ? route.continue() : route.abort('blockedbyclient')
    })
    await page.addInitScript(() => {
      window.__TAURI_INTERNALS__ = { invoke: async () => ['demo-image.png'] }
      window.$message = Object.fromEntries(['error', 'success'].map(name => [name, text => {
        const el = document.createElement('p'); el.setAttribute('role', 'status'); el.textContent = text; document.body.append(el)
      }]))
    })
    await page.route('**/src/api/index.ts*', route => route.fulfill({ contentType: 'text/javascript', body: 'export const feedbackApi = { create: async () => { window.__EM_FEEDBACK_CALLS__=(window.__EM_FEEDBACK_CALLS__||0)+1; throw Error("offline fixture") }, uploadImage: async () => { throw Error("offline fixture") } }' }))
    await page.route('**/src/components/ToolBar.vue*', route => route.fulfill({ contentType: 'text/javascript', body: 'export default {setup(p,{slots}){return()=>slots.default?.()}}' }))
    await page.route('**/src/utils/desktop/window.ts*', route => route.fulfill({ contentType: 'text/javascript', body: desktopStub }))
    await page.route('**/@tauri-apps_plugin-http.js*', route => route.fulfill({ contentType: 'text/javascript', body: 'export const fetch=globalThis.fetch.bind(globalThis)' }))
    await page.route('**/__input-check.html*', route => route.fulfill({ contentType: 'text/html', body: '<div id="app"></div><script type="module" src="/tests/input-responses-preview.ts"></script>' }))
    await page.goto(origin + '/__input-check.html')
    const submit = page.locator('.feedback-window__footer button')
    await submit.waitFor()
    assert(await submit.isDisabled(), 'empty feedback must not be submitted')
    await page.locator('.feedback-window__input input').fill('离线输入响应测试')
    await page.locator('.feedback-window__input textarea').fill('这是一条合成测试，不会发送到真实反馈服务。')
    await submit.click()
    await page.waitForFunction(() => window.__EM_FEEDBACK_CALLS__ === 1)
    await page.getByRole('status').filter({ hasText: /失败|网络|连接/ }).waitFor()
    assert(await submit.isEnabled(), 'failed requests must release the submit button')
    await page.locator('.feedback-window__image-add').click()
    await page.getByRole('status').filter({ hasText: /失败/ }).last().waitFor()
    assert(await page.locator('.feedback-window__image-add').isEnabled(), 'failed uploads must release the upload button')
    await page.goto(origin + '/__input-check.html?view=model')
    await page.getByRole('button', { name: '保存全局设置', exact: true }).click()
    await page.getByRole('status').filter({ hasText: /请输入|填写|接口|模型/ }).waitFor()
    await page.getByPlaceholder('https://api.deepseek.com/v1', { exact: true }).fill('http://127.0.0.1:19442/v1')
    await page.getByPlaceholder('例如 deepseek-flash', { exact: true }).fill('input-response-fixture')
    await page.getByRole('button', { name: '保存全局设置', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '全局模型设置已保存。' }).waitFor()
    await page.route('http://127.0.0.1:19442/v1/chat/completions', route => route.fulfill({ contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ choices: [{ message: { content: '连接成功' } }] }) }))
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '连接成功：' }).waitFor()
    await page.unroute('http://127.0.0.1:19442/v1/chat/completions')
    await page.route('http://127.0.0.1:19442/v1/chat/completions', route => route.abort('failed'))
    await page.getByRole('button', { name: '测试连接', exact: true }).click()
    await page.getByRole('status').filter({ hasText: /失败/ }).waitFor()
    assert(await page.getByRole('button', { name: '测试连接', exact: true }).isEnabled())
    assert.deepEqual(errors, [])
    const out = process.env.EM_TEST_OUTPUT || path.resolve('.preview/input-responses')
    fs.mkdirSync(out, { recursive: true })
    await page.screenshot({ path: path.join(out, 'model-inputs.png') })
    console.log('PASS: feedback validation, failed submit/upload feedback and retry; global-model validation, save, successful and failed connection tests')
  } finally {
    if (errors.length) console.error('Page errors:', errors)
    const out = process.env.EM_TEST_OUTPUT || path.resolve('.preview/input-responses')
    fs.mkdirSync(out, { recursive: true })
    await page.screenshot({ path: path.join(out, 'last-page.png'), fullPage: true }).catch(() => {})
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
